int32_t pipeline_token_kind_variant_tag(const uint8_t *variant_name, int32_t variant_len) {
  const uint8_t *p;
  const uint8_t *end;
  int32_t i;
  if (!variant_name || variant_len <= 0)
    return -1;
  p = k_token_blob;
  end = k_token_blob + sizeof(k_token_blob);
  i = 0;
  while (p < end) {
    int32_t nlen = (int32_t)p[0];
    p += 1;
    if (nlen == variant_len && memcmp(p, variant_name, (size_t)variant_len) == 0)
      return i;
    p += nlen;
    i += 1;
  }
  return -1;
}

