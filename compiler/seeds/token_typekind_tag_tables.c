int32_t pipeline_asm_typekind_variant_tag(const uint8_t *field_buf, int32_t flen) {
  size_t i;
  if (!field_buf || flen < 6)
    return -1;
  for (i = 0; i < sizeof(k_typekind) / sizeof(k_typekind[0]); i++) {
    if ((int32_t)k_typekind[i].len == flen &&
        memcmp(field_buf, k_typekind[i].name, (size_t)flen) == 0)
      return (int32_t)k_typekind[i].tag;
  }
  return -1;
}
